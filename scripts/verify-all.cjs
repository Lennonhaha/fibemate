// ---------------------------------------------------------------- runner

function execute(step) {
  const started = Date.now();
  const record = { name: step.name, id: step.id, status: 'FAIL', duration_ms: 0 };

  if (step.make) {
    const spec = step.make();
    const r = spec.spawn();
    record.duration_ms = Date.now() - started;
    record.command = spec.cmd;
    record.cwd = path.relative(ROOT, spec.cwd) || '.';
    record.exit_code = r.status;
    record.stdout_tail = tail(r.stdout);
    record.stderr_tail = tail(r.stderr);
    const out = `${r.stdout || ''}${r.stderr || ''}`;
    if (step.classify) {
      record.status = step.classify(r, spec);
    } else {
      record.status = r.status === 0 ? 'PASS' : 'FAIL';
    }
    if (record.status === 'SKIP') record.details = step.skipReason || 'skipped';
    if (r.error && r.error.code === 'ETIMEDOUT') {
      record.status = 'FAIL';
      record.details = 'timed out';
    }
    if (record.status === 'PASS' && /# fail [1-9]/.test(out)) {
      // node:test can exit 0 while reporting failures if a suite swallows them.
      record.status = 'FAIL';
      record.details = 'suite reported failures but exited 0';
    }
    return record;
  }

  try {
    const result = step.run();
    record.duration_ms = Date.now() - started;
    record.status = result.status;
    record.details = result.details;
    if (result.files) record.files = result.files;
    if (result.sha256) record.sha256 = result.sha256;
    if (result.stdout) record.stdout_tail = result.stdout;
    if (result.stderr) record.stderr_tail = result.stderr;
  } catch (e) {
    record.duration_ms = Date.now() - started;
    record.status = 'FAIL';
    record.details = e && e.message ? e.message : String(e);
  }
  return record;
}

function repoInfo() {
  const gitOut = (a) => {
    try {
      return execFileSync('git', a, { cwd: ROOT, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
    } catch {
      return '';
    }
  };
  return {
    commit: gitOut(['rev-parse', 'HEAD']),
    branch: gitOut(['rev-parse', '--abbrev-ref', 'HEAD']),
    dirty: gitOut(['status', '--porcelain']).length > 0,
  };
}

function writeReport(records) {
  const count = (s) => records.filter((r) => r.status === s).length;
  const report = {
    tool: 'verify-all',
    tool_version: '1.0.0',
    generated_at: new Date().toISOString(),
    repo: repoInfo(),
    environment: { node: process.version, platform: process.platform, arch: process.arch, cpus: os.cpus().length },
    summary: {
      total: records.length,
      pass: count('PASS'),
      fail: count('FAIL'),
      skip: count('SKIP'),
      verdict: count('FAIL') ? 'FAIL' : count('SKIP') ? 'PARTIAL' : 'PASS',
    },
    steps: records,
  };
  fs.writeFileSync(OUT, JSON.stringify(report, null, 2) + '\n', 'utf8');
  return report;
}

function printSummary(report) {
  const mark = { PASS: 'PASS', FAIL: 'FAIL', SKIP: 'SKIP' };
  for (const r of report.steps) {
    const ms = String(r.duration_ms).padStart(6);
    console.log(`  ${mark[r.status].padEnd(4)} ${ms}ms  ${r.name}`);
    if (r.status !== 'PASS' && r.details) console.log(`              ${r.details}`);
    if (r.status === 'FAIL' && r.stderr_tail && r.stderr_tail.length) {
      for (const line of r.stderr_tail.slice(-4)) console.log(`              | ${line.slice(0, 160)}`);
    }
  }
  const s = report.summary;
  console.log(`\n${s.verdict}: ${s.pass}/${s.total} pass, ${s.fail} fail, ${s.skip} skip`);
  console.log(`report: ${path.relative(process.cwd(), OUT) || OUT}`);
}

// ---------------------------------------------------------------- self-test

function selfTest() {
  // The runner must be able to report red. Two synthetic steps, one that exits 0
  // and one that exits 1, checked against the mapping the real run uses.
  const okStep = { id: 'synthetic-ok', name: 'synthetic: exits 0', make: () => node(ROOT, ['-e', 'process.exit(0)']) };
  const badStep = { id: 'synthetic-fail', name: 'synthetic: exits 1', make: () => node(ROOT, ['-e', 'console.error("deliberate"); process.exit(1)']) };
  const a = execute(okStep);
  const b = execute(badStep);
  const checks = [
    ['a zero exit is PASS', a.status === 'PASS'],
    ['a non-zero exit is FAIL', b.status === 'FAIL'],
    ['failure output is captured', (b.stderr_tail || []).some((l) => l.includes('deliberate'))],
    ['exit code is recorded', b.exit_code === 1],
  ];
  let failed = 0;
  for (const [name, ok] of checks) {
    console.log(`${ok ? 'PASS' : 'FAIL'}  ${name}`);
    if (!ok) failed++;
  }
  console.log(`\nrunner self-test: ${checks.length - failed}/${checks.length} passed`);
  process.exit(failed ? 1 : 0);
}

// ---------------------------------------------------------------- main

if (flag('selftest')) selfTest();

const selected = ONLY.length ? STEPS.filter((s) => ONLY.includes(s.id)) : STEPS;
if (!selected.length) {
  console.error(`no steps matched --only ${ONLY.join(',')}; known ids: ${STEPS.map((s) => s.id).join(', ')}`);
  process.exit(2);
}

if (!QUIET) {
  console.log(`verify-all: ${selected.length} step(s), node ${process.version}, ${process.platform}/${process.arch}`);
  console.log(`repository: ${ROOT}\n`);
}

const records = [];
for (const step of selected) {
  records.push(execute(step));
  if (!QUIET) process.stdout.write('.');
}
if (!QUIET) process.stdout.write('\n\n');

let report;
try {
  report = writeReport(records);
} catch (e) {
  console.error('could not write the evidence report:', e.message);
  process.exit(2);
}

if (!QUIET) {
  console.log('');
  printSummary(report);
}

const failed = report.summary.fail > 0;
const skipped = report.summary.skip > 0;
if (failed) process.exit(1);
if (skipped && !ALLOW_SKIP) {
  console.error('\nSKIP is not a pass. Re-run with --allow-skip if missing evidence is acceptable for this purpose.');
  process.exit(1);
}
process.exit(0);
