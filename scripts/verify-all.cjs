#!/usr/bin/env node
// SPDX-License-Identifier: GPL-3.0-only
// scripts/verify-all.cjs
//
// One command that answers "is this repository's crypto claim true right now?"
//
// The claim is not "the code compiles". It is: the ML-DSA implementation matches
// the NIST ACVP vectors, agrees byte-for-byte with an independent implementation,
// rejects non-canonical signatures, validates input lengths, ships the right
// files in its tarball, and installs and works in a directory that has never seen
// this repository. Those checks already existed — as ten separate commands with
// ten different working directories — which means the honest answer to "did you
// verify it?" was "I ran some of them once".
//
// This runs all ten, in order, and writes evidence-report.json: what ran, how
// long it took, what it printed, and what the exit code was.
//
// Exit codes:
//   0  every step PASS
//   1  at least one FAIL, or a SKIP without --allow-skip
//   2  the runner itself failed (could not write the report, etc.)
//
// A SKIP is not a pass. Missing evidence is its own verdict, and letting it exit 0
// would recreate the exact failure mode this repository keeps fixing: a green
// number that means "we did not look".
//
// Usage:
//   node scripts/verify-all.cjs
//   node scripts/verify-all.cjs --only kat,noble-parity
//   node scripts/verify-all.cjs --allow-skip --out /tmp/evidence.json
//   node scripts/verify-all.cjs --selftest     # prove the runner can report red

'use strict';

const { spawnSync, execFileSync } = require('child_process');
const fs = require('fs');
const os = require('os');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.resolve(__dirname, '..');
const PKG_DIR = path.join(ROOT, 'packages', 'fml-dsa');
const NPM = process.platform === 'win32' ? 'npm.cmd' : 'npm';

const args = process.argv.slice(2);
const flag = (name) => args.includes(`--${name}`);
const value = (name, fallback) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 && args[i + 1] ? args[i + 1] : fallback;
};

const OUT = path.resolve(ROOT, value('out', 'evidence-report.json'));
const ALLOW_SKIP = flag('allow-skip');
const QUIET = flag('quiet');
const ONLY = (value('only', '') || '').split(',').map((s) => s.trim()).filter(Boolean);

function githubToken() {
  if (process.env.GITHUB_TOKEN) return process.env.GITHUB_TOKEN;
  if (process.env.GH_TOKEN) return process.env.GH_TOKEN;
  try {
    return execFileSync('gh', ['auth', 'token'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
  } catch {
    return '';
  }
}

const tail = (text, n = 10) => {
  const lines = String(text || '').trimEnd().split('\n').filter(Boolean);
  return lines.slice(-n);
};

function node(cwd, scriptArgs, timeoutMs = 300000) {
  return { cmd: [process.execPath, ...scriptArgs].join(' '), cwd, spawn: () => spawnSync(process.execPath, scriptArgs, { cwd, encoding: 'utf8', timeout: timeoutMs, maxBuffer: 16 * 1024 * 1024 }) };
}

// ---------------------------------------------------------------- step 9

function tarballAudit() {
  const r = spawnSync(NPM, ['pack', '--dry-run', '--json'], {
    cwd: PKG_DIR,
    encoding: 'utf8',
    shell: process.platform === 'win32',
    timeout: 300000,
    maxBuffer: 16 * 1024 * 1024,
  });
  if (r.status !== 0) {
    return { status: 'FAIL', details: 'npm pack --dry-run failed', stdout: tail(r.stdout), stderr: tail(`${r.stderr || ''}`) };
  }
  let info;
  try {
    const parsed = JSON.parse(r.stdout);
    info = Array.isArray(parsed) ? parsed[0] : parsed;
  } catch (e) {
    return { status: 'FAIL', details: 'could not parse npm pack output: ' + e.message, stdout: tail(r.stdout) };
  }
  const files = (info.files || []).map((f) => f.path);
  const problems = [];
  for (const required of ['package.json', 'README.md', 'LICENSE', 'src/index.js']) {
    if (!files.includes(required)) problems.push(`missing ${required}`);
  }
  const forbidden = [
    [/^test\//, 'test files'],
    [/(^|\/)__pycache__\//, '__pycache__'],
    [/\.pyc$/, 'compiled Python'],
    [/(^|\/)kat-vectors\//, 'KAT vectors'],
    [/^bench-/, 'benchmarks'],
  ];
  for (const [re, label] of forbidden) {
    const hit = files.find((f) => re.test(f));
    if (hit) problems.push(`${label}: ${hit}`);
  }
  const details = `${files.length} files, ${(info.size / 1024).toFixed(1)} kB packed`;
  if (problems.length) return { status: 'FAIL', details: `${details}; ${problems.join('; ')}`, files };
  return { status: 'PASS', details, files };
}

// ---------------------------------------------------------------- step 10

const SMOKE_SOURCE = `// Generated by scripts/verify-all.cjs — runs against the installed tarball.
import * as pkg from 'fml-dsa';

const sets = [
  ['ml_dsa44', 1312, 2560, 2420],
  ['ml_dsa65', 1952, 4032, 3309],
  ['ml_dsa87', 2592, 4896, 4627],
];
const msg = new TextEncoder().encode('verify-all install smoke');
for (const [name, pkLen, skLen, sigLen] of sets) {
  const api = pkg[name];
  if (!api) throw new Error(name + ' is not exported');
  const seed = new Uint8Array(32).fill(7);
  const { publicKey, secretKey } = api.keygen(seed);
  if (publicKey.length !== pkLen) throw new Error(name + ' pk length ' + publicKey.length + ' != ' + pkLen);
  if (secretKey.length !== skLen) throw new Error(name + ' sk length ' + secretKey.length + ' != ' + skLen);
  const sig = api.sign(msg, secretKey);
  if (sig.length !== sigLen) throw new Error(name + ' sig length ' + sig.length + ' != ' + sigLen);
  if (api.verify(sig, msg, publicKey) !== true) throw new Error(name + ' verify failed');
  const tampered = Uint8Array.from(msg);
  tampered[0] ^= 0xff;
  if (api.verify(sig, tampered, publicKey) !== false) throw new Error(name + ' accepted a tampered message');
  const again = api.sign(msg, secretKey);
  if (Buffer.compare(Buffer.from(sig), Buffer.from(again)) !== 0) throw new Error(name + ' signature is not deterministic');
}
console.log('SMOKE OK: 44/65/87 keygen, sign, verify, tamper-reject, determinism');
`;

function installSmoke() {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'fml-dsa-verify-'));
  const appDir = path.join(tmp, 'app');
  try {
    const packed = spawnSync(NPM, ['pack', '--pack-destination', tmp], {
      cwd: PKG_DIR,
      encoding: 'utf8',
      shell: process.platform === 'win32',
      timeout: 300000,
      maxBuffer: 16 * 1024 * 1024,
    });
    if (packed.status !== 0) {
      return { status: 'FAIL', details: 'npm pack failed', stderr: tail(packed.stderr) };
    }
    const tgzName = tail(packed.stdout, 1)[0];
    if (!tgzName || !tgzName.endsWith('.tgz')) {
      return { status: 'FAIL', details: 'could not read tarball name from npm pack', stdout: tail(packed.stdout) };
    }
    const tgz = path.join(tmp, tgzName);
    const bytes = fs.readFileSync(tgz);
    const sha256 = crypto.createHash('sha256').update(bytes).digest('hex');

    fs.mkdirSync(appDir, { recursive: true });
    fs.writeFileSync(path.join(appDir, 'package.json'), JSON.stringify({ name: 'fml-dsa-smoke', private: true, type: 'module' }, null, 2));
    const installed = spawnSync(NPM, ['install', tgz, '--no-audit', '--no-fund', '--loglevel=error'], {
      cwd: appDir,
      encoding: 'utf8',
      shell: process.platform === 'win32',
      timeout: 600000,
      maxBuffer: 16 * 1024 * 1024,
    });
    if (installed.status !== 0) {
      return { status: 'FAIL', details: 'npm install of the packed tarball failed', stderr: tail(installed.stderr) };
    }
    fs.writeFileSync(path.join(appDir, 'smoke.mjs'), SMOKE_SOURCE);
    const ran = spawnSync(process.execPath, ['smoke.mjs'], { cwd: appDir, encoding: 'utf8', timeout: 300000 });
    const out = `${ran.stdout || ''}${ran.stderr || ''}`;
    if (ran.status !== 0 || !out.includes('SMOKE OK')) {
      return { status: 'FAIL', details: 'installed package failed the round-trip', stdout: tail(out) };
    }
    return {
      status: 'PASS',
      details: `installed ${tgzName} (sha256 ${sha256.slice(0, 12)}…) and ran 44/65/87 round-trip`,
      sha256,
    };
  } finally {
    // The path is one we just created with mkdtemp; refusing anything else keeps a
    // typo from turning cleanup into a delete.
    if (tmp.startsWith(os.tmpdir()) && path.basename(tmp).startsWith('fml-dsa-verify-')) {
      fs.rmSync(tmp, { recursive: true, force: true });
    }
  }
}

