    exports: [
      { func: 'ml_dsa44', type: 'ml-dsa-instance', params: ['seed','msg'], sizes: [32, 64] },
      { func: 'ml_dsa65', type: 'ml-dsa-instance', params: ['seed','msg'], sizes: [32, 64] },
      { func: 'ml_dsa87', type: 'ml-dsa-instance', params: ['seed','msg'], sizes: [32, 64] },
    ],
